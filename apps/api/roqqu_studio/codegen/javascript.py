"""Deterministic flow -> JavaScript codegen (Node 18+, ES module, no dependencies).

The twin of codegen/python.py: same graph walk, same Roqqu API Service
endpoints (roqqu-api-services.gitbook.io/ras, base https://service.roqqu.com/v1),
same guards. One
async function per block, run() for the trigger's chain and an exported
handle* per webhook root. Uses the global fetch, so `node flow.mjs` just runs.
"""

from __future__ import annotations

import json
import re

from ..ir.models import Node, Workflow
from ..providers import default_catalog
from ..providers.base import Catalog
from .python import _ENDPOINTS, _PUBLIC, _SEND_TYPES, _cfg, _num, _reachable

_CUST = '{ email: "jean@email.com", first_name: "Jean", last_name: "Billy" }'

_HEADER = """/**
 * {name} - generated by Roqqu Studio.
 *
 * Deterministic code from your flow graph: no AI wrote this file, and the same
 * flow always produces the same code. Each function is one block on your canvas.
 * run() executes the trigger's chain in graph order; every webhook becomes its
 * own exported handle* function you mount on a route.
 *
 * Roqqu API Service: https://roqqu-api-services.gitbook.io/ras  (base https://service.roqqu.com/v1)
 * Keys: RAS console -> Settings -> API Keys and Webhooks.
 * Run it:  RAS_TEST_KEY=... node {filename}      (Node 18 or newer, no installs)
 * A test key never moves real money; RAS_LIVE_KEY does.
 */
import crypto from "node:crypto";
import {{ pathToFileURL }} from "node:url";

const BASE_URL = process.env.ROQQU_BASE_URL ?? "https://service.roqqu.com/v1";
const NETWORK = process.env.ROQQU_NETWORK ?? "trc20"; // bitcoin, trc20, bep20, erc20, ...
const COIN = process.env.ROQQU_COIN ?? "usdt";
const TEST_KEY = process.env.RAS_TEST_KEY ?? "";
const API_KEY = TEST_KEY || (process.env.RAS_LIVE_KEY ?? "");
// RAS reads a test key from x-staging-api-key and a live key from x-api-key.
const KEY_HEADER = TEST_KEY ? "x-staging-api-key" : "x-api-key";

/** A safety block said no. Money must NOT move past this point. */
export class GuardFailed extends Error {{}}

/** One RAS call (form-encoded). Unwraps the {{status, message, data}} envelope or throws. */
async function roqqu(method, path, {{ query, body, auth = true }} = {{}}) {{
  const url = new URL(BASE_URL + path);
  for (const [k, v] of Object.entries(query ?? {{}})) {{
    if (v !== undefined && v !== "") url.searchParams.set(k, String(v));
  }}
  const headers = {{ accept: "application/json" }};
  if (auth) {{
    if (!API_KEY) throw new Error("Set RAS_TEST_KEY (or RAS_LIVE_KEY) from the RAS console");
    headers[KEY_HEADER] = API_KEY;
  }}
  let payload;
  if (method !== "GET") {{
    headers["content-type"] = "application/x-www-form-urlencoded";
    const form = new URLSearchParams();
    for (const [k, v] of Object.entries(body ?? {{}})) {{
      if (v !== undefined) form.set(k, typeof v === "object" ? JSON.stringify(v) : String(v));
    }}
    payload = form.toString();
  }}
  const res = await fetch(url, {{ method, headers, body: payload }});
  const json = await res.json().catch(() => ({{ status: "fail", message: `HTTP ${{res.status}}` }}));
  if (!res.ok || json.status !== "success") {{
    throw new Error(json.message || `Roqqu request failed (HTTP ${{res.status}})`);
  }}
  return json.data;
}}

const seenReferences = new Set();
"""


def _fn_name(node: Node) -> str:
    """A stable camelCase JavaScript function name for a node."""
    parts = [p for p in re.split(r"[^a-zA-Z0-9]+", node.id) if p]
    if not parts:
        return "block"
    name = parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:])
    return f"n{name[0].upper()}{name[1:]}" if name[0].isdigit() else name


def _js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def _doc(node: Node, catalog: Catalog) -> str:
    try:
        d = catalog.resolve(node.type)
    except KeyError:
        return f"/** {node.label or node.type}. */"
    lines = ["/**", f" * {node.label or d.title} ({node.type})."]
    if d.when_to_use:
        lines += [" *", f" * When to use: {d.when_to_use}"]
    if d.doc_url:
        lines += [" *", f" * Docs: {d.doc_url}"]
    lines.append(" */")
    return "\n".join(lines)


def _rows(node: Node) -> list[str]:
    rows = node.config.get("rows")
    rows = rows if isinstance(rows, list) else []
    out = [
        "  // The people this flow pays, straight from your sheet. Edit freely.",
        "  // amount is in COIN (e.g. USDT); wallet is their address on NETWORK.",
        "  ctx.payouts = [",
    ]
    for i, row in enumerate(rows):
        if not isinstance(row, dict):
            continue
        out.append(
            "    { name: %s, amount: %s, wallet: %s },"
            % (
                _js(str(row.get("name") or f"Payee {i + 1}")),
                f"{_num(row.get('amount')):g}",
                _js(str(row.get("wallet") or row.get("address") or "")),
            )
        )
    return out + ["  ];", "  return ctx;"]


def _body(node: Node) -> list[str]:
    t = node.type
    if t == "app.data_rows":
        return _rows(node)
    if t == "roqqu.batch_send":
        return [
            "  // RAS has no batch endpoint: one Send call per row. Each returns a refid;",
            "  // the on-chain confirmation arrives later as the token_sent webhook.",
            "  for (const leg of ctx.payouts ?? []) {",
            '    const sent = await roqqu("POST", "/wallets/send", { body: { amount: leg.amount, network: NETWORK, to: leg.wallet, token: COIN } });',
            "    leg.refid = sent.refid;",
            "  }",
            "  return ctx;",
        ]
    if t in _SEND_TYPES:
        return [
            "  // Send Coin: crypto from your Roqqu balance to one address (fee comes out of it).",
            '  const sent = await roqqu("POST", "/wallets/send", {',
            f"    body: {{ amount: ctx.amount ?? 0, network: NETWORK, to: ctx.to ?? {_js(str(_cfg(node, 'to', 'wallet', 'address')))}, token: COIN }},",
            "  });",
            "  ctx.transfer_reference = sent.refid;",
            "  return ctx;",
        ]
    if t == "roqqu.payment_link":
        return [
            "  // A hosted Roqqu checkout priced in NGN; RAS makes one address per network.",
            '  const link = await roqqu("POST", "/payment-links", {',
            "    body: {",
            f"      amount: ctx.amount ?? {_js(_cfg(node, 'amount', default=1000))},",
            '      amount_currency: "ngn",',
            "      customer_details: ctx.customer ?? %s," % _CUST,
            '      payment_reference: ctx.payment_reference ?? crypto.randomBytes(10).toString("hex"),',
            f"      success_url: {_js(str(_cfg(node, 'success_url', default='https://yourwebsite.com/payment/success')))},",
            f"      cancel_url: {_js(str(_cfg(node, 'cancel_url', default='https://yourwebsite.com/payment/cancel')))},",
            '      wallets: [{ network: "bitcoin", token: "BTC" }, { network: "trc20", token: "USDT" }, { network: "bep20", token: "USDT" }],',
            "    },",
            "  });",
            "  ctx.checkout_url = link.payment_link;",
            "  ctx.payment_reference = link.payment_reference;",
            "  ctx.wallets = link.wallets ?? [];",
            "  return ctx;",
        ]
    if t in ("roqqu.generate_wallet", "roqqu.invoice_wallet", "roqqu.member_wallet"):
        return [
            "  // A deposit address on NETWORK for this customer (RAS needs email + names).",
            '  const wallet = await roqqu("POST", "/wallets/generate-wallet", {',
            "    body: { network: NETWORK, customer: ctx.customer ?? %s }," % _CUST,
            "  });",
            "  ctx.address = wallet.address;",
            "  return ctx;",
        ]
    if t == "roqqu.blockchain_address":
        return [
            "  // What Network: the destination must belong to the network we send on.",
            '  const networks = (await roqqu("POST", "/wallets/what-network", {',
            f"    body: {{ address: ctx.to ?? {_js(str(_cfg(node, 'address', 'to')))} }},",
            "  })) ?? [];",
            "  if (!networks.includes(NETWORK)) throw new GuardFailed(`address is not on ${NETWORK} (found ${networks})`);",
            "  return ctx;",
        ]
    if t == "roqqu.tx_status":
        return [
            "  // The queued send record: queued, sent or refunded.",
            '  ctx.send_record = await roqqu("GET", `/transaction/refId/${ctx.transfer_reference ?? ""}`);',
            "  return ctx;",
        ]
    if t == "roqqu.get_wallets":
        return [
            "  // Authoritative: what actually landed on our deposit address.",
            '  const addresses = (await roqqu("POST", "/wallets/get-addresses", { body: { network: NETWORK } })) ?? [];',
            "  const mine = addresses.find((w) => w.address === ctx.address);",
            '  if (!mine) throw new GuardFailed("deposit address is not one of our addresses");',
            "  ctx.paid_amount = Number(mine.total_received ?? 0);",
            "  return ctx;",
        ]
    if t in _ENDPOINTS:
        method, path = _ENDPOINTS[t]
        payload = "query" if method == "GET" else "body"
        auth = ", auth: false" if t in _PUBLIC else ""
        return [
            "  const scalars = Object.fromEntries(Object.entries(ctx).filter(([, v]) => typeof v !== \"object\"));",
            f"  const input = {{ ...{_js(node.config or {})}, ...scalars }};",
            f'  const data = await roqqu("{method}", "{path}", {{ {payload}: input{auth} }});',
            "  Object.assign(ctx, data && typeof data === \"object\" && !Array.isArray(data) ? data : { data });",
            "  return ctx;",
        ]
    if t == "safety.verify_signature":
        return [
            "  // RAS encrypts webhook bodies with YOUR API key (AES-256-CTR); the IV is the",
            "  // x-api-key request header. Only a body that decrypts to JSON is from Roqqu.",
            "  let event;",
            "  try {",
            '    const decipher = crypto.createDecipheriv("aes-256-ctr", API_KEY.substring(0, 32), Buffer.from(payload?._iv ?? "", "hex"));',
            '    event = JSON.parse(Buffer.concat([decipher.update(Buffer.from(payload?.hash ?? "", "hex")), decipher.final()]).toString());',
            "  } catch {",
            '    throw new GuardFailed("webhook does not decrypt with our key: not Roqqu");',
            "  }",
            "  Object.assign(ctx, event.meta_data ?? {}, { event_type: event.event_type });",
            "  return ctx;",
        ]
    if t == "safety.validate_amount":
        expected = _num(node.config.get("expected_amount", 0))
        return [
            "  // Paid must cover expected. Compare in kobo so float rounding never decides.",
            f"  const expected = Math.round(Number(ctx.expected_amount ?? {expected:g}) * 100);",
            "  const paid = Math.round(Number(ctx.paid_amount ?? 0) * 100);",
            "  if (paid < expected) throw new GuardFailed(`underpaid: ${paid / 100} of ${expected / 100}`);",
            "  return ctx;",
        ]
    if t == "safety.idempotency_guard":
        return [
            "  // Process each payment reference exactly once.",
            "  const ref = ctx.payment_reference ?? ctx.address;",
            "  if (seenReferences.has(ref)) throw new GuardFailed(`duplicate delivery: ${ref} already handled`);",
            "  seenReferences.add(ref);",
            "  return ctx;",
        ]
    if t == "safety.balance_guard":
        return [
            "  // Check your balance covers the payout BEFORE moving money.",
            "  // Put ctx.balance from your own ledger or the Get Balances block (POST /balances).",
            "  if (Number(ctx.balance ?? 0) < Number(ctx.amount ?? 0)) {",
            "    throw new GuardFailed(`insufficient balance: ${ctx.balance} < ${ctx.amount}`);",
            "  }",
            "  return ctx;",
        ]
    if t.startswith("safety."):
        return ["  // Guard checkpoint: keep this before any money-moving call.", "  return ctx;"]
    if t.startswith("event."):
        return [
            "  // Webhook/event handler stub: pass the JSON body plus the x-api-key header",
            "  // as payload._iv so the decrypt block can read it.",
            "  Object.assign(ctx, payload ?? {});",
            "  return ctx;",
        ]
    if t == "custom.code":
        return [
            "  // Code Block: your snippet was written in Python on the canvas.",
            "  // Port it here; read and modify ctx, then return it.",
            "  return ctx;",
        ]
    if t.startswith("app.notify"):
        message = _cfg(node, "message", "text", default="Payment confirmed with Roqqu.")
        return [
            "  // Tell the customer or your team. Swap console.log for WhatsApp or email.",
            f"  console.log(`[notify] ${{{_js(str(message))}}} (${{(ctx.payouts ?? []).length || 1}} recipient(s))`);",
            "  return ctx;",
        ]
    return [f"  (ctx.log ??= []).push({_js(node.label or t)});", "  return ctx;"]


def generate_javascript(
    workflow: Workflow, catalog: Catalog | None = None, *, filename: str = "flow.mjs"
) -> str:
    catalog = catalog or default_catalog()
    roots = [workflow.entrypoint] if workflow.entrypoint else []
    roots += [r for r in workflow.roots() if r not in roots]
    entry = roots[0] if roots else (workflow.nodes[0].id if workflow.nodes else None)

    spine = _reachable(workflow, entry) if entry else []
    emitted = {n.id for n in spine}
    handlers: list[tuple[Node, list[Node]]] = []
    for root in roots[1:]:
        if root in emitted:
            continue
        chain = [n for n in _reachable(workflow, root) if n.id not in emitted]
        if chain:
            emitted.update(n.id for n in chain)
            handlers.append((workflow.node(root), chain))
    orphans = [n for n in workflow.nodes if n.id not in emitted]

    parts = [_HEADER.format(name=workflow.name, filename=filename)]
    for node in [*spine, *(n for _, c in handlers for n in c), *orphans]:
        parts.append(
            "\n".join([
                _doc(node, catalog),
                f"export async function {_fn_name(node)}(ctx, payload) {{",
                *_body(node),
                "}",
                "",
            ])
        )

    run = [f"/** Run the flow from its trigger, in graph order: {workflow.name}. */",
           "export async function run() {", "  let ctx = {};"]
    run += [f"  ctx = await {_fn_name(n)}(ctx);" for n in spine]
    run += ["  return ctx;", "}", ""]
    parts.append("\n".join(run))

    for root, chain in handlers:
        steps = [n for n in chain if not n.type.startswith("event.")]
        name = _fn_name(root)
        block = [
            f"/** Mount on your webhook route (POST /roqqu/webhook): {root.label or root.type}. */",
            f"export async function handle{name[:1].upper()}{name[1:]}(payload) {{",
            "  let ctx = { ...(payload ?? {}) };",
        ]
        block += [f"  ctx = await {_fn_name(n)}(ctx, payload);" for n in steps]
        block += ["  return ctx;", "}", ""]
        parts.append("\n".join(block))

    parts.append("\n".join([
        "// node flow.mjs runs the flow once and prints the result.",
        "if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {",
        "  run()",
        "    .then((ctx) => console.log(ctx))",
        "    .catch((err) => {",
        "      console.error(err.message);",
        "      process.exitCode = 1;",
        "    });",
        "}",
        "",
    ]))
    return "\n".join(parts)
