# Documented endpoint per node type (developers.roqqu.com, base
# https://api.roqqu.com/prod/v1). Codegen-local on purpose: the catalog stays
# transport-neutral.
_ENDPOINTS: dict[str, tuple[str, str]] = {
    "roqqu.generate_wallet": ("POST", "/user/generate-wallet"),
    "roqqu.invoice_wallet": ("POST", "/user/generate-wallet"),
    "roqqu.member_wallet": ("POST", "/user/generate-wallet"),
    "roqqu.get_wallets": ("POST", "/user/wallets"),
    "roqqu.delete_wallet": ("POST", "/user/delete-wallet"),
    "roqqu.token_price": ("GET", "/price"),
    "roqqu.bvn_verify": ("POST", "/user/bvn-verify"),
    "roqqu.nin_verify": ("POST", "/user/nin-verify"),
    "roqqu.recharge_airtime": ("POST", "/user/recharge-airtime"),
    "roqqu.pay_electric": ("POST", "/user/pay-electric"),
    "roqqu.verify_meter": ("GET", "/verify-meter"),
}
_SEND_TYPES = {"roqqu.send_token", "roqqu.split_send", "roqqu.refund_send"}

_HEADER = '''"""{name} - generated by Roqqu Studio.

Deterministic codegen from your flow graph (#146): no LLM wrote this file,
the same flow always generates the same code. Each function is one block on
your whiteboard. run() executes the trigger's chain in graph order; every
webhook becomes its own handle_* you mount on a route (never called inline).

Roqqu API (https://developers.roqqu.com): set ROQQU_SECRET_KEY (RQ-SEC-...,
dashboard -> Security) and ROQQU_WEBHOOK_SECRET in your environment. Roqqu has
no sandbox: every call here hits production and moves real crypto.
"""

from __future__ import annotations

import os
import uuid
from decimal import Decimal

import httpx

BASE_URL = os.getenv("ROQQU_BASE_URL", "https://api.roqqu.com/prod/v1")
TOKEN = os.getenv("ROQQU_PAY_TOKEN", "trx")  # btc, eth or trx for wallets


class GuardFailed(Exception):
    """A safety block said no. Money must NOT move past this point."""


def _token(client: httpx.Client) -> str:
    """Roqqu authorizes with the secret key itself as a bearer token
    (docs: https://developers.roqqu.com/reference/authorization)."""
    return os.environ["ROQQU_SECRET_KEY"]


def _data(resp: httpx.Response):
    """Unwrap Roqqu's envelope {{status, message, data}}; raise on failure."""
    resp.raise_for_status()
    body = resp.json()
    if body.get("status") != "success":
        raise RuntimeError(body.get("message") or "Roqqu request failed")
    return body.get("data")
'''


def _identifier(node: Node) -> str:
    """A stable python function name for a node."""
    raw = re.sub(r"[^a-z0-9_]+", "_", node.id.lower()).strip("_") or "block"
    if raw[0].isdigit():
        raw = f"n_{raw}"
    return raw


def _reachable(workflow: Workflow, start: str) -> list[Node]:
    """Nodes reachable from `start` in graph order (the engine's walk, #8)."""
    order: list[Node] = []
    seen: set[str] = set()
    adjacency: dict[str, list[str]] = {}
    for edge in workflow.edges:
        adjacency.setdefault(edge.source, []).append(edge.target)
    queue: deque[str] = deque([start])
    while queue:
        node_id = queue.popleft()
        if node_id in seen:
            continue
        seen.add(node_id)
        order.append(workflow.node(node_id))
        queue.extend(adjacency.get(node_id, []))
    return order


def _docstring(node: Node, catalog: Catalog) -> str:
    try:
        d = catalog.resolve(node.type)
    except KeyError:
        return f'    """{node.label or node.type}."""'
    lines = [f'    """{node.label or d.title} ({node.type}).']
    if d.when_to_use:
        lines += ["", f"    When to use: {d.when_to_use}"]
    if d.doc_url:
        lines += ["", f"    Docs: {d.doc_url}"]
    lines.append('    """')
    return "\n".join(lines)


def _config_literal(node: Node) -> str:
    if not node.config:
        return "{}"
    inner = ", ".join(f'"{k}": {v!r}' for k, v in node.config.items())
    return "{" + inner + "}"


def _num(value: object) -> float:
    try:
        return float(str(value))
    except (TypeError, ValueError):
        return 0.0


def _cfg(node: Node, *keys: str, default: object = "") -> object:
    for key in keys:
        if key in node.config and node.config[key] not in (None, ""):
            return node.config[key]
    return default


def _rows_literal(node: Node) -> list[str]:
    """Turn the Employee List sheet into the payout legs, baked into the
    generated code so a Run actually pays those people (in crypto, per row)."""
    rows = node.config.get("rows")
    rows = rows if isinstance(rows, list) else []
    lines = [
        "    # The people this flow pays, straight from your sheet. Edit freely.",
        "    # amount is in the token (e.g. TRX); wallet is their address.",
        '    ctx["payouts"] = [',
    ]
    for i, row in enumerate(rows):
        if not isinstance(row, dict):
            continue
        name = str(row.get("name") or f"Payee {i + 1}")
        wallet = str(row.get("wallet") or row.get("address") or "")
        lines.append(
            f'        {{"name": {name!r}, "amount": {_num(row.get("amount")):g}, "wallet": {wallet!r}}},'
        )
    lines += ["    ]", "    return ctx"]
    return lines


def _body(node: Node) -> list[str]:
    """The function body for one block. Config the dev typed rides along."""
    t = node.type
    if t == "app.data_rows":
        return _rows_literal(node)
    if t == "roqqu.batch_send":
        return [
            "    # Roqqu has no batch endpoint: one Send Token call per row.",
            '    for leg in ctx.get("payouts", []):',
            "        _data(client.post(",
            '            f"{BASE_URL}/user/send-{TOKEN}",',
            '            headers={"Authorization": f"Bearer {token}"},',
            '            json={"amount": leg["amount"], "wallet": leg["wallet"]},',
            "        ))",
            '        leg["status"] = "sent"',
            "    return ctx",
        ]
    if t in _SEND_TYPES:
        return [
            "    # Send Token: crypto from your Roqqu balance to one address.",
            "    _data(client.post(",
            '        f"{BASE_URL}/user/send-{TOKEN}",',
            '        headers={"Authorization": f"Bearer {token}"},',
            "        json={",
            '            "amount": float(ctx.get("amount", 0)),',
            f'            "wallet": ctx.get("wallet", {_cfg(node, "wallet", "address")!r}),',
            "        },",
            "    ))",
            "    return ctx",
        ]
    if t == "roqqu.blockchain_address":
        return [
            "    # Chain lookup. Roqqu allows 1 call per 100 s; more = 10 h IP ban.",
            "    data = _data(client.get(",
            '        f"{BASE_URL}/blockchain/address",',
            '        params={"symbol": TOKEN, "addr": ctx.get("address", "")},',
            "    ))",
            '    ctx["chain"] = data',
            "    return ctx",
        ]
    if t == "roqqu.account_resolve":
        return [
            "    # Resolve the account holder's name before money moves.",
            '    ctx["account_name"] = _data(client.post(',
            '        f"{BASE_URL}/user/account-resolve",',
            '        headers={"Authorization": f"Bearer {token}"},',
            "        json={",
            f'            "account_number": ctx.get("account_number", {_cfg(node, "account_number")!r}),',
            f'            "bank": ctx.get("bank", {_cfg(node, "bank")!r}),',
            "        },",
            "    ))",
            "    return ctx",
        ]
    if t == "roqqu.get_wallets":
        return [
            "    # Authoritative: what actually landed on our deposit address.",
            "    wallets = _data(client.post(",
            '        f"{BASE_URL}/user/wallets",',
            '        headers={"Authorization": f"Bearer {token}"},',
            '        json={"token": TOKEN},',
            "    )) or []",
            '    mine = next((w for w in wallets if w["address"] == ctx.get("address")), None)',
            "    if mine is None:",
            '        raise GuardFailed("deposit address is not one of our wallets")',
            '    ctx["paid_amount"] = Decimal(str(mine.get("total_received") or 0))',
            "    return ctx",
        ]
    if t in _ENDPOINTS:
        method, path = _ENDPOINTS[t]
        call = "client.get" if method == "GET" else "client.post"
        payload = "params" if method == "GET" else "json"
        return [
            f"    body = {{**{_config_literal(node)}, **ctx}}",
            f"    data = _data({call}(",
            f'        f"{{BASE_URL}}{path}",',
            '        headers={"Authorization": f"Bearer {token}"},',
            f"        {payload}=body,",
            "    ))",
            "    ctx.update(data if isinstance(data, dict) else {\"data\": data})",
            "    return ctx",
        ]
    if t == "safety.verify_signature":
        return [
            "    # Roqqu echoes the secret you set on the dashboard in the webhook body.",
            "    import hmac",
            '    expected = os.getenv("ROQQU_WEBHOOK_SECRET", "")',
            '    sent = str((payload or ctx).get("secret", ""))',
            "    if not expected or not hmac.compare_digest(expected.encode(), sent.encode()):",
            '        raise GuardFailed("webhook secret mismatch: not Roqqu")',
            "    return ctx",
        ]
    if t == "safety.validate_amount":
        return [
            "    # Paid must cover expected, compared exactly - never with floats.",
            f'    expected = Decimal(str(ctx.get("expected_amount", {node.config.get("expected_amount", 0)!r})))',
            '    paid = Decimal(str(ctx.get("amountPaid", ctx.get("paid_amount", "0"))))',
            "    if paid < expected:",
            '        raise GuardFailed(f"underpaid: {paid} of {expected}")',
            "    return ctx",
        ]
    if t == "safety.idempotency_guard":
        return [
            "    # Process each payment reference exactly once.",
            '    ref = ctx.get("paymentReference") or ctx.get("payment_reference")',
            "    if ref in _SEEN_REFERENCES:",
            '        raise GuardFailed(f"duplicate delivery: {ref} already handled")',
            "    _SEEN_REFERENCES.add(ref)",
            "    return ctx",
        ]
    if t == "safety.balance_guard":
        return [
            "    # Check your balance covers the payout BEFORE moving money (MON012).",
            "    # Roqqu documents no balance endpoint: supply ctx['balance'] from your",
            "    # own ledger (or the Roqqu dashboard) before this block runs.",
            '    balance = Decimal(str(ctx.get("balance", "0")))',
            '    amount = Decimal(str(ctx.get("amount", "0")))',
            "    if balance < amount:",
            '        raise GuardFailed(f"insufficient balance: {balance} < {amount}")',
            "    return ctx",
        ]
    if t.startswith("safety."):
        return [
            "    # Guard checkpoint: keep this before any money-moving call.",
            "    return ctx",
        ]
    if t.startswith("event."):
        return [
            "    # Webhook/event handler stub: mount this on your framework's route",
            "    # (e.g. POST /roqqu/webhook) and pass the parsed payload in.",
            "    ctx.update(payload or {})",
            "    return ctx",
        ]
    if t == "custom.code":
        code = str(node.config.get("code", "")).rstrip()
        if code:
            snippet = ["    # --- your code block (verbatim from the whiteboard, #147) ---"]
            snippet += [f"    {line}" if line.strip() else "" for line in code.splitlines()]
            snippet += ["    # --- end code block ---", "    return ctx"]
            return snippet
        return [
            "    # Code Block: put your logic here. Read/modify ctx and return it.",
            "    return ctx",
        ]
    if t.startswith("app.notify"):
        return [
            "    # Tell the customer / your team. Swap print() for your own",
            "    # WhatsApp or email provider.",
            "    paid = len(ctx.get(\"payouts\", [])) or 1",
            f'    message = {_cfg(node, "message", "text", default="Payment confirmed with Roqqu.")!r}',
            '    print(f"[notify] {message} ({paid} recipient(s))")',
            "    return ctx",
        ]
    # app.* and anything else: a plain step that records what it did.
    return [
        f'    ctx.setdefault("log", []).append("{node.label or t}")',
        "    return ctx",
    ]


def generate_python(workflow: Workflow, catalog: Catalog | None = None) -> str:
    """The whole module: header, one function per block, and wiring that matches
    the graph - the entrypoint chain runs in run(); every other event root (a
    webhook) becomes its own handler you mount on a route, never called inline."""
    catalog = catalog or default_catalog()
    roots = [workflow.entrypoint] if workflow.entrypoint else []
    roots += [r for r in workflow.roots() if r not in roots]
    entry = roots[0] if roots else (workflow.nodes[0].id if workflow.nodes else None)

    spine = _reachable(workflow, entry) if entry else []
    emitted: set[str] = {n.id for n in spine}

    handler_chains: list[tuple[Node, list[Node]]] = []
    for root in roots[1:]:
        if root in emitted:
            continue
        chain = [n for n in _reachable(workflow, root) if n.id not in emitted]
        if not chain:
            continue
        emitted.update(n.id for n in chain)
        handler_chains.append((workflow.node(root), chain))

    orphans = [n for n in workflow.nodes if n.id not in emitted]

    parts: list[str] = [_HEADER.format(name=workflow.name)]
    parts.append("_SEEN_REFERENCES: set[str] = set()\n")

    def _emit_fn(node: Node) -> None:
        fn = _identifier(node)
        signature = f"def {fn}(ctx: dict, *, client: httpx.Client, token: str, "
        if node.type.startswith("event.") or node.type == "safety.verify_signature":
            signature += "payload: dict | None = None, "
        signature = signature.rstrip(", ") + ") -> dict:"
        parts.append("\n".join(["", signature, _docstring(node, catalog), *_body(node)]))

    for node in spine:
        _emit_fn(node)
    for _root, chain in handler_chains:
        for node in chain:
            _emit_fn(node)
    for node in orphans:
        _emit_fn(node)

    spine_calls = [
        f"        ctx = {_identifier(n)}(ctx, client=client, token=token)" for n in spine
    ]
    body: list[str] = [
        "",
        "",
        "def run() -> dict:",
        f'    """Run the flow from its trigger, in graph order: {workflow.name}."""',
        "    ctx: dict = {}",
        "    with httpx.Client(timeout=30.0) as client:",
        "        token = _token(client)",
        *(spine_calls or ["        pass  # nothing on the entrypoint spine"]),
        "    return ctx",
    ]

    for root, chain in handler_chains:
        steps = [n for n in chain if not n.type.startswith("event.")]
        calls = [
            f"        ctx = {_identifier(n)}(ctx, client=client, token=token)" for n in steps
        ]
        body += [
            "",
            "",
            f"def handle_{_identifier(root)}(payload: dict) -> dict:",
            f'    """Mount on your webhook route (POST /roqqu/webhook): '
            f'{root.label or root.type}."""',
            "    ctx: dict = dict(payload or {})",
            "    with httpx.Client(timeout=30.0) as client:",
            "        token = _token(client)",
            *(calls or ["        pass"]),
            "    return ctx",
        ]

    body += ["", "", 'if __name__ == "__main__":', "    print(run())", ""]
    parts.append("\n".join(body))
    return "\n".join(parts)
